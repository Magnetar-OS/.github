#!/usr/bin/env python3
"""Put the shared header and footer on every Magnetar-OS repository's README.

The header is the repository's banner (drawn by build.py) and a row of link
buttons; the footer is the suite's icon strip. Both sit between marker
comments, so running this again replaces them in place instead of stacking a
second copy. The first run on a README replaces its `# Title` line, which the
banner takes over.

Edits README.md in each checkout beside this one and nothing else — committing
is left to whoever runs it, because those checkouts may hold other work.

    python3 tools/readmes.py [repo ...]     # default: every repo in build.REPOS
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

from build import APPS, REPOS, ROOT, Repo

ASSETS = 'https://raw.githubusercontent.com/Magnetar-OS/.github/main/profile/assets'
ORG = 'https://github.com/Magnetar-OS'

HEAD_OPEN = '<!-- magnetar:header — generated by Magnetar-OS/.github tools/readmes.py; edit it there -->'
HEAD_CLOSE = '<!-- /magnetar:header -->'
FOOT_OPEN = '<!-- magnetar:footer — generated by Magnetar-OS/.github tools/readmes.py; edit it there -->'
FOOT_CLOSE = '<!-- /magnetar:footer -->'


def themed(name: str, alt: str, height: int) -> str:
    return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="{ASSETS}/{name}-dark.svg">'
            f'<img src="{ASSETS}/{name}-light.svg" height="{height}" alt="{alt}"></picture>')


def has_releases(repo: str) -> bool:
    out = subprocess.run(['gh', 'api', f'repos/Magnetar-OS/{repo}/releases?per_page=1'],
                         check=True, capture_output=True, text=True).stdout
    return bool(json.loads(out))


def header(r: Repo) -> str:
    alt = f'{r.name} — {r.tagline}'.replace('"', '&quot;')
    pills = [f'<a href="https://magnetaros.com"><img src="{ASSETS}/pill-site.svg" height="40" alt="magnetaros.com"></a>']
    if has_releases(r.repo):
        pills.append(f'<a href="{ORG}/{r.repo}/releases">{themed("pill-releases", "Releases", 40)}</a>')
    pills.append(f'<a href="https://github.com/orgs/Magnetar-OS/repositories">{themed("pill-repos", "All repositories", 40)}</a>')
    return f'''{HEAD_OPEN}
<div align="center">

<img src="{ASSETS}/repos/{r.repo}.svg" width="100%" alt="{alt}">
<br><br>
{'&nbsp;\n'.join(pills)}

<p></p>

</div>
{HEAD_CLOSE}'''


def footer() -> str:
    icons = '&nbsp;\n'.join(f'<a href="{ORG}/{a.slug}"><img src="{ASSETS}/icons/{a.slug}.svg" width="36" alt="{a.name}"></a>'
                            for a in APPS)
    return f'''{FOOT_OPEN}
<br>

<div align="center">

{icons}

<sub>Part of <a href="{ORG}"><b>Magnetar</b></a> — COSMIC on CachyOS · <a href="https://magnetaros.com">magnetaros.com</a></sub>

</div>
{FOOT_CLOSE}'''


def block(open_: str, close: str) -> re.Pattern[str]:
    return re.compile(re.escape(open_.split(' — ')[0]) + r'.*?' + re.escape(close), re.S)


def apply(r: Repo) -> None:
    path = ROOT.parent / r.repo / 'README.md'
    text = path.read_text()
    head, foot = block(HEAD_OPEN, HEAD_CLOSE), block(FOOT_OPEN, FOOT_CLOSE)

    if head.search(text):
        text = head.sub(lambda _: header(r), text, count=1)
    else:
        first, _, rest = text.partition('\n')
        if not first.startswith('# '):
            raise SystemExit(f'{path}: expected a "# Title" first line to replace, found {first!r}')
        text = f'{header(r)}\n{rest}'

    if foot.search(text):
        text = foot.sub(lambda _: footer(), text, count=1)
    else:
        text = f'{text.rstrip()}\n\n{footer()}\n'

    path.write_text(text)
    print(f'updated {path.relative_to(ROOT.parent)}')


def main() -> None:
    wanted = sys.argv[1:]
    known = {r.repo: r for r in REPOS}
    unknown = [w for w in wanted if w not in known]
    if unknown:
        raise SystemExit(f'not in build.REPOS: {", ".join(unknown)}')
    for r in (known[w] for w in wanted) if wanted else REPOS:
        apply(r)


if __name__ == '__main__':
    main()
